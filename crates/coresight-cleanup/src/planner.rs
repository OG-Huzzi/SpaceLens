//! The planner: evidence → opportunities → reversible plan.
//!
//! The planner reads a [`UsageReport`] (already aggregated facts) and
//! emits a [`CleanupPlan`] whose items are **category-level
//! opportunities** with full reasoning. It never touches the disk and
//! never deletes anything — it only proposes.
//!
//! Category policy (docs/SECURITY_AND_SAFETY.md protection domains):
//!
//! * **Safe**: Cache, TemporaryData, Logs — regenerable by definition;
//!   moving them to Trash is reversible and the consequence is bounded.
//! * **Review**: Downloads, Development, Archives — the user must read
//!   the reasoning; these are never auto-selected.
//! * **OffLimits**: Applications, ApplicationData, Documents, Images,
//!   Video, Audio, Games, SystemData, UserData, Other, Unknown — these
//!   are user content or system state. They are **never** proposed as
//!   actionable at the category level; duplicates/big files inside them
//!   are future per-file tools with their own evidence rules.

use coresight_classifier::Category;
use coresight_insights::UsageReport;
use serde::{Deserialize, Serialize};

use crate::{ActionKind, CleanupItem, CleanupPlan, SafetyTier};

/// Knobs for the planner. Defaults are conservative.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PlannerOptions {
    /// Include `Review` tier opportunities (default false — the planner
    /// stays silent on anything the user has not asked to review).
    pub include_review: bool,
    /// Minimum recoverable bytes for an opportunity to be proposed.
    pub min_recoverable_bytes: u64,
}

impl PlannerOptions {
    /// Safe defaults: only `Safe` items, any positive size.
    pub fn safe_defaults() -> Self {
        PlannerOptions {
            include_review: false,
            min_recoverable_bytes: 1,
        }
    }
}

/// The safety tier a category gets at the **category-total** level.
/// Per-file tools (duplicate/big-file) refine these with evidence.
pub fn tier_for_category(category: Category) -> SafetyTier {
    match category {
        Category::Cache | Category::TemporaryData | Category::Logs => SafetyTier::Safe,
        Category::Downloads | Category::Development | Category::Archives => SafetyTier::Review,
        _ => SafetyTier::OffLimits,
    }
}

/// The human title for a category opportunity.
fn title_for(category: Category) -> &'static str {
    match category {
        Category::Applications => "Applications",
        Category::ApplicationData => "Application data",
        Category::Games => "Games",
        Category::Documents => "Documents",
        Category::Images => "Images",
        Category::Video => "Video",
        Category::Audio => "Audio",
        Category::Downloads => "Downloads",
        Category::Archives => "Archives",
        Category::Development => "Development",
        Category::TemporaryData => "Temporary data",
        Category::Cache => "Cache",
        Category::Logs => "Logs",
        Category::Backups => "Backups",
        Category::SystemData => "System data",
        Category::UserData => "User data",
        Category::Other => "Other",
        Category::Unknown => "Unknown",
    }
}

fn why_for(category: Category, bytes: u64) -> String {
    match tier_for_category(category) {
        SafetyTier::Safe => format!(
            "{bytes} bytes of {category:?} data can be regenerated by the apps that created it, so removing it frees space without losing user content.",
            category = title_for(category).to_lowercase()
        ),
        SafetyTier::Review => format!(
            "{bytes} bytes in {}. These may include files you still need, so review before acting.",
            title_for(category).to_lowercase()
        ),
        SafetyTier::OffLimits => String::new(),
    }
}

fn what_stays_for(category: Category) -> String {
    match tier_for_category(category) {
        SafetyTier::Safe => format!(
            "All {} outside the {} category stays untouched. No file is deleted permanently; everything goes to Trash/quarantine first.",
            "data",
            title_for(category).to_lowercase()
        ),
        SafetyTier::Review => format!(
            "Only items you explicitly confirm are moved. Everything else in {} stays untouched.",
            title_for(category).to_lowercase()
        ),
        SafetyTier::OffLimits => format!(
            "All {} is off-limits and is never proposed as actionable.",
            title_for(category).to_lowercase()
        ),
    }
}

fn consequence_for(category: Category) -> String {
    match tier_for_category(category) {
        SafetyTier::Safe => format!(
            "Apps that need this {} data will regenerate it on next launch. The files remain recoverable from Trash/quarantine until you empty it.",
            title_for(category).to_lowercase()
        ),
        SafetyTier::Review => "Removing these files may require re-downloading or rebuilding them. Nothing is deleted permanently before you confirm.".to_string(),
        SafetyTier::OffLimits => String::new(),
    }
}

/// Build a reversible cleanup plan from one snapshot's usage report.
///
/// The plan is a *proposal*, not an execution. The caller must run it
/// through [`validate_plan`](crate::validate::validate_plan) and show
/// the user the [`CleanupPreview`](crate::preview::CleanupPreview)
/// before any adapter is allowed to act.
pub fn plan_cleanup(report: &UsageReport, options: &PlannerOptions) -> CleanupPlan {
    let mut items: Vec<CleanupItem> = Vec::new();
    let mut off_limits_excluded: Vec<Category> = Vec::new();

    for (i, &category) in Category::ALL.iter().enumerate() {
        let totals = report.category.get(i).copied().unwrap_or_default();
        if totals.logical_size == 0 {
            continue;
        }
        let tier = tier_for_category(category);
        if tier == SafetyTier::OffLimits {
            off_limits_excluded.push(category);
            continue;
        }
        if tier == SafetyTier::Review && !options.include_review {
            continue;
        }
        if totals.logical_size < options.min_recoverable_bytes {
            continue;
        }
        let title = title_for(category);
        items.push(CleanupItem {
            id: format!("{}:{}", category.code(), totals.logical_size),
            category,
            title: title.to_string(),
            why_recommended: why_for(category, totals.logical_size),
            recoverable_bytes: totals.logical_size,
            tier,
            what_stays_untouched: what_stays_for(category),
            consequence: consequence_for(category),
            destination: Some("OS Trash / app quarantine".to_string()),
            undo: Some("Restore from Trash/quarantine".to_string()),
            action: ActionKind::MoveToTrash,
        });
    }

    // Deterministic: tier (Safe first), then largest bytes, then code.
    items.sort_by(|a, b| {
        a.tier
            .cmp(&b.tier)
            .then_with(|| b.recoverable_bytes.cmp(&a.recoverable_bytes))
            .then_with(|| a.category.code().cmp(b.category.code()))
    });

    let total_recoverable_bytes = items
        .iter()
        .fold(0u64, |acc, it| acc.saturating_add(it.recoverable_bytes));

    CleanupPlan {
        id: format!(
            "plan:{}:{}:{}",
            report.scanned_entries,
            total_recoverable_bytes,
            items.len()
        ),
        items,
        total_recoverable_bytes,
        partial: report.errored_entries > 0 || report.entries_without_size > 0,
        off_limits_excluded,
    }
}
